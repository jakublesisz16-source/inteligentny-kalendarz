import { readFileSync } from 'node:fs';
const read = (path) => readFileSync(path, 'utf8');
const work = read('src/work/WorkView.tsx');
const finance = read('src/finance/FinanceDashboardView.tsx');
const css = read('src/styles/interface-refinement.css');
const version = read('src/core/version.ts');
const build = read('src/core/build.ts');
const sw = read('public/service-worker.js');
const checks = [];
const check = (name, ok) => { if (!ok) throw new Error(`FAIL: ${name}`); checks.push(name); };
check('Work tab is remembered locally', work.includes("WORK_TAB_STORAGE_KEY = 'ik.work.tab'") && work.includes('localStorage.setItem(WORK_TAB_STORAGE_KEY, workTab)'));
check('Work uses controlled single shift expansion', work.includes('expandedShiftId') && work.includes("current === event.id ? null : event.id"));
check('Whole Work row is the summary target', work.includes('work-shift-row-trigger') && work.includes('aria-expanded={expanded}'));
check('Work exposes calm person count and chevron', work.includes('work-shift-team-count') && work.includes('work-shift-chevron'));
check('Finance scope is remembered locally', finance.includes("FINANCE_SCOPE_STORAGE_KEY = 'ik.finance.scope'") && finance.includes('localStorage.setItem(FINANCE_SCOPE_STORAGE_KEY, financeScope)'));
check('Finance keeps transaction-first month behavior', finance.includes("useState<FinanceExpenseListMode>('TRANSACTIONS')"));
check('Mobile bottom-nav clearance is explicit', css.includes('--mobile-bottom-nav-clearance: calc(76px + max(8px, env(safe-area-inset-bottom)))'));
check('View shell keeps extra clearance above fixed nav', css.includes('padding-bottom: calc(var(--mobile-bottom-nav-clearance) + 24px) !important'));
check('Interactive rows get subtle press feedback', css.includes('.finance-expense-row:active') && css.includes('.work-shift-row-trigger:active'));
check('Old absolute Work count control is neutralized', css.includes('position: static !important') && css.includes('content: none !important'));
const vm = version.match(/APP_VERSION = '(\d+\.\d+\.\d+\.(\d+))'/); const bm = build.match(/APP_BUILD = '(\d+)'/);
check('Build212 metadata remains valid on later builds', Boolean(vm && bm && Number(vm[2]) >= 212 && bm[1] === vm[2] && sw.includes(`v${vm[1]}`)));
check('Database schema remains 14', version.includes('DATABASE_SCHEMA_VERSION = 14'));
console.log(`Build212 usability system proof PASS ${checks.length}/${checks.length}`);
